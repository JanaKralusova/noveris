#!/usr/bin/env node
/* eslint-disable no-console */
'use strict';

/*
 * Data-driven service pages: content/services/<id>.json -> /sluzby/<id>/index.html (+ EN twin).
 *
 *   { "sk": { "sections": [...] }, "en": { "sections": [...] } | null }
 *
 * Each section is { "type": ..., ...props } as accepted by ui.renderSections(). Photos are given as
 * { "name": "<PH key>", "alt": "..." } and resolve to /assets/photos/services/<name>. The hero gets the
 * breadcrumb (Domov > Služby > [parent >] page) automatically. Title/description live in content/pages.json.
 */

const fs = require('fs');
const path = require('path');
const site = require('./lib/site');
const layout = require('./lib/layout');
const schema = require('./lib/schema');
const ui = require('./lib/ui');

const { ROOT, PAGES, SERVICES, abs } = site;
const GENERATED = '<!-- Generated by scripts/build-services.js – edit content/services/ and content/pages.json instead -->';
const HOME_NAME = { sk: 'Domov', en: 'Home' };
const SERVICES_NAME = { sk: 'Služby', en: 'Services' };

function fail(msg) {
  console.error('build-services: ERROR: ' + msg);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

// Default `sizes` per place the photo is used (matches the component layout).
const SIZES = {
  hero: '(min-width: 1024px) 52vw, 100vw',
  splitBand: '(min-width: 1024px) 48vw, 100vw',
  contactBand: '(min-width: 1024px) 50vw, 1px',
  // Card photos on phones are lazy and decorative: they are declared as 320px wide (a card is really viewport - 50px),
  // so a 1.75x phone picks the 560w file (about 1.5x density) instead of 800w, which keeps the hero's bandwidth.
  cardSide: '(min-width: 1024px) 56vw, (min-width: 640px) 90vw, 320px',
  cardTop: '(min-width: 1024px) 33vw, (min-width: 640px) 50vw, 320px',
  cardCompact: '(min-width: 1024px) 20vw, (min-width: 640px) 50vw, 320px',
  splitTextList: '(min-width: 768px) 50vw, 100vw',
  relatedBand: '(min-width: 1024px) 30vw, (min-width: 640px) 80vw, 320px',
};

function resolvePhoto(p, sizes, eager) {
  if (!p) return p;
  if (!p.name) fail('photo without "name"');
  return { src: `/assets/photos/services/${p.name}`, alt: p.alt || '', sizes: p.sizes || sizes, eager: !!eager };
}

function prepare(sections, crumbs, lang, crumbsLabel) {
  return sections.map((s) => {
    const o = { ...s };
    if (o.link) o.link = localizeLink(o.link, lang);
    if (o.cta) o.cta = localizeLink(o.cta, lang);
    if (o.photo) o.photo = resolvePhoto(o.photo, SIZES[o.type] || SIZES.splitBand, o.type === 'hero');
    if (o.items && o.type !== 'grid') {
      o.items = o.items.map((it) => {
        if (!it || typeof it !== 'object') return it;
        const r = { ...it };
        if (r.photo) r.photo = resolvePhoto(r.photo, SIZES[o.type.replace(/^cards(\w)/, (_, c) => 'card' + c)] || SIZES.cardSide, false);
        if (r.link) r.link = localizeLink(r.link, lang);
        return r;
      });
    }
    if (o.type === 'hero') { o.crumbs = crumbs; o.crumbsLabel = crumbsLabel; }
    if (o.type === 'grid') o.items = prepare(o.items, crumbs, lang, crumbsLabel);
    return o;
  });
}

function loadService(id) {
  const file = path.join(ROOT, 'content', 'services', `${id}.json`);
  if (!fs.existsSync(file)) fail(`missing ${path.relative(ROOT, file)} for service "${id}"`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function pageTitleOf(data) {
  const hero = (data.sections || []).find((s) => s.type === 'hero');
  if (!hero) fail('service page without a hero section');
  return hero.title;
}

// hasContent: the page is built (URL + copy exist). isHidden: built, but noindex, unpaired and unlinked
// (SERVICES[id].hidden[lang]). hasLang: built and visible - the only state that gets hreflang, sitemap,
// llms.txt and card links.
const hasContent = (id, lang) => !!(SERVICES[id][lang] && loadService(id)[lang]);
const isHidden = (id, lang) => !!(SERVICES[id].hidden && SERVICES[id].hidden[lang]);
const hasLang = (id, lang) => hasContent(id, lang) && !isHidden(id, lang);

// Internal links on a non-Slovak page: a link to a service page of that language that is not visible
// yet points to its Slovak twin; every link outside the language's URL space (Slovak pages, articles)
// is marked hreflang/lang="sk". Other hrefs are left as they are.
const SK_ATTRS = 'hreflang="sk" lang="sk"';
function localLink(href, lang) {
  if (lang === 'sk' || !href || !href.startsWith('/')) return { href };
  const target = Object.keys(SERVICES).find((id) => SERVICES[id][lang] === href);
  if (target && !hasLang(target, lang)) return { href: SERVICES[target].sk, attrs: SK_ATTRS };
  if (href.startsWith(`/${lang}/`)) return { href };
  return { href, attrs: SK_ATTRS };
}
const localizeLink = (link, lang) => (link && link.href ? { ...link, ...localLink(link.href, lang) } : link);

function render(id, lang, ctx) {
  const svc = SERVICES[id];
  const data = loadService(id)[lang];
  const meta = (ctx.pages[id] || {})[lang];
  if (!meta || !meta.title || !meta.description) fail(`content/pages.json: missing title/description for ${id}/${lang}`);
  const url = svc[lang];
  const canonical = abs(url);

  const chain = [];
  for (let p = svc.parent; p; p = SERVICES[p].parent) chain.unshift(p);
  const crumbList = [
    { name: HOME_NAME[lang], url: PAGES.home[lang] },
    { name: SERVICES_NAME[lang], url: PAGES.services[lang] },
    ...chain.map((p) => ({ name: pageTitleOf(loadService(p)[lang] || loadService(p).sk), ...localLink(SERVICES[p][lang] || SERVICES[p].sk, lang) })).map(({ href, ...c }) => ({ ...c, url: href })),
    { name: pageTitleOf(data), url },
  ];

  const crumbsLabel = site.loadTranslations()[lang]['ui.breadcrumb'];
  const main = ui.renderSections(prepare(data.sections, crumbList, lang, crumbsLabel));

  const pair = hasLang(id, 'sk') && hasLang(id, 'en');
  const og = site.OG_IMAGES[lang];
  const image = abs(og.path);
  const pageUrl = canonical;
  const nodes = schema.pageNodes({
    url: pageUrl, name: meta.title, description: meta.description, lang, image, imageAlt: site.OG_ALT[lang],
    crumbs: crumbList.map((c) => ({ name: c.name, url: abs(c.url) })),
    extra: { mainEntity: schema.ref(`${pageUrl}#service`) },
  });
  nodes.push(schema.serviceNode({ url: pageUrl, name: pageTitleOf(data), description: meta.description, lang }));

  const head = {
    title: meta.title,
    description: meta.description,
    keywords: meta.keywords,
    canonical,
    robots: isHidden(id, lang) ? 'noindex' : undefined,
    alternates: pair
      ? [{ hreflang: 'sk', href: abs(svc.sk) }, { hreflang: 'en', href: abs(svc.en) }, { hreflang: 'x-default', href: abs(svc.sk) }]
      : [],
    og: {
      type: 'website', title: meta.title, image, imageWidth: og.width, imageHeight: og.height, imageAlt: site.OG_ALT[lang],
      alternateLocales: pair ? [layout.LOCALES[lang === 'sk' ? 'en' : 'sk']] : [],
    },
    jsonlds: [schema.graph(lang, nodes)],
  };

  return layout.renderDocument({
    generated: GENERATED, lang, active: 'services',
    switchTo: pair ? { sk: svc.sk, en: svc.en } : null,
    head, main, bodyScripts: '',
  });
}

// Every built service page: [{ id, lang, url, hidden, title }] (title = the page H1). Hidden pages are built but must stay out of
// the sitemap, llms.txt and every link.
function outputs() {
  const list = [];
  for (const id of Object.keys(SERVICES)) {
    for (const lang of ['sk', 'en']) if (hasContent(id, lang)) list.push({ id, lang, url: SERVICES[id][lang], hidden: isHidden(id, lang), title: pageTitleOf(loadService(id)[lang]) });
  }
  return list;
}

function main() {
  const outRoot = path.resolve(arg('out') || ROOT);
  const ctx = { pages: site.loadPagesData() };
  let n = 0;
  for (const o of outputs()) {
    const dest = site.urlToFile(outRoot, o.url);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, render(o.id, o.lang, ctx));
    n++;
  }
  console.log(`build-services: ${n} pages written`);
}

if (require.main === module) main();

module.exports = { main, outputs, render, hasLang, hasContent, isHidden, loadService, pageTitleOf };
