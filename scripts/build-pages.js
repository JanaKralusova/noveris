const { ROOT, PAGES, SERVICES, abs } = site;
const GENERATED = '<!-- Generated by scripts/build-pages.js – edit templates/ and content/ instead -->';
const LANGS = ['sk', 'en'];

function fail(msg) {
  console.error('build-pages: ERROR: ' + msg);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

// ---------------------------------------------------------------- i18n

// Replace the whole inner HTML of every [data-i18n] element with its translation
// (like the old runtime did) and drop the attribute. Handles nested same-name tags.
function applyI18n(html, t, lang, file) {
  const openRe = /<([a-zA-Z][a-zA-Z0-9]*)\b([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>/g;
  let out = '';
  let pos = 0;
  let m;
  while ((m = openRe.exec(html))) {
    const [full, tag, before, key, after] = m;
    if (t[key] === undefined) fail(`${file}: missing ${lang} translation "${key}"`);
    const contentStart = m.index + full.length;
    const closeRe = new RegExp(`<(/?)${tag}(?=[\\s>/])[^>]*>`, 'g');
    closeRe.lastIndex = contentStart;
    let depth = 1;
    let end = -1;
    let c;
    while ((c = closeRe.exec(html))) {
      if (c[1]) { if (--depth === 0) { end = c.index; break; } }
      else if (!/\/>$/.test(c[0])) depth++;
    }
    if (end === -1) fail(`${file}: unclosed <${tag}> for data-i18n="${key}"`);
    out += html.slice(pos, m.index) + `<${tag}${before}${after}>` + t[key];
    pos = end;
    openRe.lastIndex = end;
  }
  out += html.slice(pos);
  return out;
}

function applyPlaceholders(html, t, lang, file) {
  return html.replace(/\sdata-i18n-placeholder="([^"]+)"([^>]*?)\splaceholder="[^"]*"/g, (_, key, mid) => {
    if (t[key] === undefined) fail(`${file}: missing ${lang} translation "${key}"`);
    return `${mid} placeholder="${layout.esc(t[key])}"`;
  });
}

// phone="m640,m813," adds a phone-only crop (<source media="(max-width: 767px)">).
// variants="480,640," lists the width suffixes ascending (empty = the full-size file); default is "480,".
// {{picture src="/assets/photos/home" alt="i18n.key" sizes="…" class="…" style="…" eager}}
function applyPictures(html, t, lang, file) {
  return html.replace(/\{\{picture\s+([^}]*)\}\}/g, (_, attrs) => {
    const a = {};
    attrs.replace(/([a-z]+)="([^"]*)"|\b(eager)\b/g, (m, k, v, flag) => { if (flag) a.eager = true; else a[k] = v; return m; });
    if (t[a.alt] === undefined) fail(`${file}: missing ${lang} translation "${a.alt}"`);
    return picture({ src: a.src, sizes: a.sizes, alt: t[a.alt], eager: !!a.eager, variants: a.variants ? a.variants.split(',') : undefined, art: a.phone ? { media: '(max-width: 767px)', variants: a.phone.split(',') } : undefined, cls: a.class || '', style: a.style || '' });
  });
}

// {{#sak}}…{{/sak}} renders only when a SAK number is configured; the number links to the
// SAK register profile when one is listed in sameAs.person.
function applySak(html, config) {
  const block = /\{\{#sak\}\}([\s\S]*?)\{\{\/sak\}\}/g;
  if (!config.sakNumber) return html.replace(block, '');
  const profile = config.sameAs.person.find((u) => /^https:\/\/(www\.)?sak\.sk\//.test(u));
  const num = profile
    ? `<a href="${layout.esc(profile)}" class="text-copper underline underline-offset-2 hover:text-forest">${layout.esc(config.sakNumber)}</a>`
    : layout.esc(config.sakNumber);
  return html.replace(block, (_, inner) => inner.replace('{{sakNumber}}', num));
}

// {{#linkedin}}…{{/linkedin}} renders only when a LinkedIn URL is listed in sameAs.person.
function applyLinkedIn(html, config) {
  const block = /\{\{#linkedin\}\}([\s\S]*?)\{\{\/linkedin\}\}/g;
  const url = config.sameAs.person.find((u) => /^https:\/\/([a-z]+\.)?linkedin\.com\//.test(u));
  if (!url) return html.replace(block, '');
  return html.replace(block, (_, inner) => inner.replace('{{linkedinUrl}}', layout.esc(url)));
}

function applyLatest(html, lang, copy, articles, t) {
  const c = copy.homeLatestArticles[lang];
  const pick = latest(articles, 3);
  const cards = pick.map((a) => ui.articleCard({
    photo: { src: `/assets/articles/${a.image}`, variants: ['400', '640', '800', '1024', ''], fallback: '800', sizes: ARTICLE_SIZES, alt: a.imageAlt },
    title: a.title, text: a.excerpt, href: `/clanky/${a.slug}/`, linkText: t['home.articles.read'], attrs: lang === 'sk' ? '' : 'lang="sk"',
  }));
  const cta = ui.button(c.cta, '/clanky/', { variant: 'outline', attrs: lang === 'sk' ? '' : 'hreflang="sk" lang="sk"' });
  return html
    .replace('{{latest:label}}', layout.esc(c.label))
    .replace('{{latest:h2}}', c.h2Html)
    .replace('{{latest:cta}}', () => cta)
    .replace('{{latest:tiles}}', () => cards.join('\n'));
}

// The six practice areas, in display order, with their card icon and photo (assets/photos/services).
const AREAS = [
  { id: 'vysporiadanie-pozemkov', icon: 'terrain', homeIcon: 'landscape', photo: 's_land' },
  { id: 'nehnutelnosti-a-development', icon: 'domain', photo: 's_dev' },
  { id: 'zmluvna-agenda', icon: 'description', photo: 's_contract' },
  { id: 'obcianske-pravo', icon: 'balance', photo: 's_civil' },
  { id: 'obchodne-pravo', icon: 'business_center', photo: 's_biz' },
  { id: 'riesenie-sporov', icon: 'gavel', photo: 's_court' },
];
const CARD_SIZES = '(min-width: 1024px) 17vw, (min-width: 640px) 34vw, 100vw';

// Card link: the page of the language when it is visible, otherwise the Slovak page (labelled as such).
function areaLink(id, lang, t) {
  if (hasLang(id, lang)) return { href: SERVICES[id][lang], text: t['services.card.more'], attrs: '' };
  return { href: SERVICES[id].sk, text: lang === 'sk' ? t['services.card.more'] : t['services.card.moreSk'], attrs: lang === 'sk' ? '' : 'hreflang="sk"' };
}

// {{services:cards}}: side cards with photo (services page); {{services:iconCards}}: icon cards (home).
function applyServices(html, t, lang) {
  const items = (kind) => AREAS.map((a) => {
    const link = areaLink(a.id, lang, t);
    const base = { title: t[`services.area.${a.id}.title`], href: link.href };
    if (kind === 'icon') return { ...base, icon: a.homeIcon || a.icon, text: t[`services.area.${a.id}.desc`], linkText: link.text, attrs: link.attrs };
    return { ...base, icon: a.icon, paras: [t[`services.area.${a.id}.desc`]], link, photo: { src: `/assets/photos/services/${a.photo}`, alt: '', sizes: CARD_SIZES } };
  });
  return html
    .replace('{{services:cards}}', () => ui.cardGrid('side', items('side')))
    .replace('{{services:iconCards}}', () => ui.cardGrid('icon', items('icon')));
}

// {{services:hero}}: the services page header (breadcrumb, label, title, intro, photo).
function applyServicesHero(html, t, lang) {
  return html.replace('{{services:hero}}', () => ui.hero({
    crumbs: [{ name: t['nav.home'], url: PAGES.home[lang] }, { name: t['nav.services'], url: PAGES.services[lang] }],
    crumbsLabel: t['ui.breadcrumb'],
    label: t['services.hero.label'],
    title: t['services.hero.h1'],
    intro: [t['services.hero.desc']],
    photo: { src: '/assets/photos/services/s_hero', alt: '', sizes: '(min-width: 1024px) 52vw, 100vw', eager: true },
  }));
}

// {{contactBand:band1}}: closing contact band (dark green) with a photo from assets/photos/services.
function applyContactBand(html, t, lang) {
  return html.replace(/\{\{contactBand:([a-z0-9_]+)\}\}/g, (_, name) => ui.contactBand({
    eyebrow: t['nav.contact'],
    title: t['cta.h2'],
    paras: [t['cta.desc']],
    cta: { text: t['cta.btn'], href: PAGES.contact[lang] },
    photo: { src: `/assets/photos/services/${name}`, alt: '', sizes: '(min-width: 1024px) 50vw, 1px' },
  }));
}

// {{ui:button page=contact text=cta.btn variant=primary}}, {{ui:link page=about text=home.hero.cta2}}:
// ui.js buttons / arrow links whose label is a translation key and whose target is a page id.
function applyUi(html, t, lang, file) {
  return html.replace(/\{\{ui:(button|link)\s+([^}]*)\}\}/g, (_, kind, attrs) => {
    const a = {};
    attrs.replace(/([a-z]+)=(\S+)/g, (m, k, v) => { a[k] = v; return m; });
    if (t[a.text] === undefined) fail(`${file}: missing ${lang} translation "${a.text}"`);
    const p = PAGES[a.page];
    if (!p) fail(`${file}: unknown page id in {{ui:${kind} page=${a.page}}}`);
    const href = p[lang] || p.sk;
    return kind === 'button' ? ui.button(t[a.text], href, { variant: a.variant || 'primary' }) : ui.linkArrow(t[a.text], href);
  });
}

// {{t:key}}: a translation as escaped plain text (for attribute values).
function applyT(html, t, lang, file) {
  return html.replace(/\{\{t:([A-Za-z0-9_.-]+)\}\}/g, (_, key) => {
    if (t[key] === undefined) fail(`${file}: missing ${lang} translation "${key}"`);
    return layout.esc(t[key]);
  });
}

// Owners page: counts and source line come from the index written by build-owners-data.js
// (stats are omitted when the index has not been generated yet).
function applyOwners(html) {
  const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'owners.json'), 'utf8'));
  const metaFile = path.join(ROOT, 'data', 'nezisteni-vlastnici', 'meta.json');
  const meta = fs.existsSync(metaFile) ? JSON.parse(fs.readFileSync(metaFile, 'utf8')) : null;
  const nf = (n) => n.toLocaleString('sk-SK').replace(/\s/g, '\u00a0');
  const [y, m, d] = cfg.asOf.split('-').map(Number);
  const asOf = `${d}. ${m}. ${y}`.replace(/ /g, '\u00a0');
  const stats = meta ? `${nf(meta.rows)} záznamov · ${nf(meta.areas)} katastrálnych území · stav k ${asOf}` : `stav k ${asOf}`;
  return html
    .replace('{{owners:stats}}', stats)
    .replace('{{owners:link}}', () => ui.linkArrow('Prečítajte si viac o možnostiach vysporiadania pozemkov a vlastníckych vzťahov.', SERVICES['vysporiadanie-pozemkov'].sk))
    .replace(/\{\{owners:asOf\}\}/g, asOf)
    .replace('{{owners:sourcePage}}', layout.esc(cfg.sourcePage));
}

function applyUrls(html, lang, file) {
  return html.replace(/\{\{url:([a-z]+)\}\}/g, (_, id) => {
    if (id === 'articles') return '/clanky/';
    const p = PAGES[id];
    if (!p) fail(`${file}: unknown page id in {{url:${id}}}`);
    return p[lang] || p.sk;
  });
}

