#!/usr/bin/env node
/* eslint-disable no-console */
'use strict';

/*
 * Static generator for the main site pages (SK + EN).
 *
 *   node scripts/build-pages.js [--out DIR]
 *
 * Reads templates/pages/*.html (markup with data-i18n hooks and {{url:id}}
 * link tokens), translations.js and content/pages.json, and writes real
 * crawlable pages: /, /o-nas/, /sluzby/, /kontakt/, /ochrana-osobnych-udajov/,
 * /en/, /en/about/, /en/services/, /en/contact/ and /404.html. Zero dependencies.
 */

const fs = require('fs');
const path = require('path');
const site = require('./lib/site');
const layout = require('./lib/layout');
const schema = require('./lib/schema');
const { picture } = require('./lib/images');
const { tile, latest } = require('./lib/components');
const { loadArticles } = require('./build-articles');

const { ROOT, PAGES, abs } = site;
const GENERATED = '<!-- Generated by scripts/build-pages.js — edit templates/ and content/ instead -->';
const LANGS = ['sk', 'en'];

function fail(msg) {
  console.error('build-pages: ERROR: ' + msg);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

// ---------------------------------------------------------------- i18n

// Replace the whole inner HTML of every [data-i18n] element with its translation
// (like the old runtime did) and drop the attribute. Handles nested same-name tags.
function applyI18n(html, t, lang, file) {
  const openRe = /<([a-zA-Z][a-zA-Z0-9]*)\b([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>/g;
  let out = '';
  let pos = 0;
  let m;
  while ((m = openRe.exec(html))) {
    const [full, tag, before, key, after] = m;
    if (t[key] === undefined) fail(`${file}: missing ${lang} translation "${key}"`);
    const contentStart = m.index + full.length;
    const closeRe = new RegExp(`<(/?)${tag}(?=[\\s>/])[^>]*>`, 'g');
    closeRe.lastIndex = contentStart;
    let depth = 1;
    let end = -1;
    let c;
    while ((c = closeRe.exec(html))) {
      if (c[1]) { if (--depth === 0) { end = c.index; break; } }
      else if (!/\/>$/.test(c[0])) depth++;
    }
    if (end === -1) fail(`${file}: unclosed <${tag}> for data-i18n="${key}"`);
    out += html.slice(pos, m.index) + `<${tag}${before}${after}>` + t[key];
    pos = end;
    openRe.lastIndex = end;
  }
  out += html.slice(pos);
  return out;
}

function applyPlaceholders(html, t, lang, file) {
  return html.replace(/\sdata-i18n-placeholder="([^"]+)"([^>]*?)\splaceholder="[^"]*"/g, (_, key, mid) => {
    if (t[key] === undefined) fail(`${file}: missing ${lang} translation "${key}"`);
    return `${mid} placeholder="${layout.esc(t[key])}"`;
  });
}

// {{picture src="/assets/photos/home" alt="i18n.key" sizes="…" class="…" style="…" eager}}
function applyPictures(html, t, lang, file) {
  return html.replace(/\{\{picture\s+([^}]*)\}\}/g, (_, attrs) => {
    const a = {};
    attrs.replace(/([a-z]+)="([^"]*)"|\b(eager)\b/g, (m, k, v, flag) => { if (flag) a.eager = true; else a[k] = v; return m; });
    if (t[a.alt] === undefined) fail(`${file}: missing ${lang} translation "${a.alt}"`);
    return picture({ src: a.src, sizes: a.sizes, alt: t[a.alt], eager: !!a.eager, cls: a.class || '', style: a.style || '' });
  });
}

// Links to the Slovak-only service page; on English pages the link is marked as Slovak.
function applyServiceLink(html, lang, copy) {
  return html
    .replace(/\{\{serviceLinkAttrs\}\}/g, lang === 'sk' ? '' : ' hreflang="sk" lang="sk"')
    .replace(/\{\{serviceLink\}\}/g, layout.esc(copy.serviceLink[lang]));
}

function applyLatest(html, lang, copy, articles) {
  const c = copy.homeLatestArticles[lang];
  return html
    .replace('{{latest:label}}', layout.esc(c.label))
    .replace('{{latest:h2}}', c.h2Html)
    .replace('{{latest:cta}}', layout.esc(c.cta))
    .replace('{{latestCtaAttrs}}', lang === 'sk' ? '' : ' hreflang="sk" lang="sk"')
    .replace('{{latest:tiles}}', () => latest(articles, 3).map((a) => tile(a, { level: 3, lang })).join('\n'));
}

function applyUrls(html, lang, file) {
  return html.replace(/\{\{url:([a-z]+)\}\}/g, (_, id) => {
    if (id === 'articles') return '/clanky/';
    if (id === 'land') return site.serviceUrl('vysporiadanie-pozemkov');
    const p = PAGES[id];
    if (!p) fail(`${file}: unknown page id in {{url:${id}}}`);
    return p[lang] || p.sk;
  });
}

// ---------------------------------------------------------------- page assembly

const CONTACT_MSG = {
  sk: {
    sending: 'Odosiela sa...',
    success: '✓ Správa bola úspešne odoslaná. Ozveme sa vám čo najskôr.',
    failure: '✗ Správu sa nepodarilo odoslať. Skúste to prosím znova.',
    error: '✗ Nastala chyba. Kontaktujte nás prosím priamo e-mailom.',
  },
  en: {
    sending: 'Sending...',
    success: '✓ Message sent successfully. We will get back to you soon.',
    failure: '✗ Failed to send message. Please try again.',
    error: '✗ An error occurred. Please contact us directly by email.',
  },
};

// Old hash-routed links (/#about …) keep working: forward them to the real pages.
const HASH_REDIRECT = `<script>
(function () {
    var map = ${JSON.stringify({ '#about': PAGES.about.sk, '#services': PAGES.services.sk, '#contact': PAGES.contact.sk, '#privacy': PAGES.privacy.sk })};
    var target = map[location.hash];
    if (target) location.replace(target);
})();
</script>`;

const PAGE_TYPES = { about: 'AboutPage', contact: 'ContactPage' };
const PRIVACY_NAME = 'Ochrana osobných údajov';

function render(id, lang, ctx) {
  const file = `templates/pages/${id}.html`;
  const tpl = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const t = ctx.translations[lang];
  let main = applyI18n(tpl, t, lang, file);
  main = applyPlaceholders(main, t, lang, file);
  main = applyPictures(main, t, lang, file);
  main = applyServiceLink(main, lang, ctx.copy);
  main = applyLatest(main, lang, ctx.copy, ctx.articles);
  main = applyUrls(main, lang, file);

  const data = (ctx.pages[id] || {})[lang];
  if (!data || !data.title || !data.description) fail(`content/pages.json: missing title/description for ${id}/${lang}`);

  const p = PAGES[id];
  const hasPair = !!(p && p.en);
  const is404 = id === '404';
  const canonical = is404 ? null : abs(p[lang]);
  const og = site.OG_IMAGES[lang];
  const image = abs(og.path);

  const verification = [];
  if (id === 'home' && lang === 'sk') {
    if (ctx.config.googleSiteVerification) verification.push(`<meta name="google-site-verification" content="${layout.esc(ctx.config.googleSiteVerification)}"/>`);
    if (ctx.config.bingSiteVerification) verification.push(`<meta name="msvalidate.01" content="${layout.esc(ctx.config.bingSiteVerification)}"/>`);
  }

  let jsonlds = [];
  if (!is404) {
    const crumbs = id === 'home' ? null : [
      { name: t['nav.home'], url: abs(PAGES.home[lang]) },
      { name: id === 'privacy' ? PRIVACY_NAME : t['nav.' + id], url: canonical },
    ];
    jsonlds = [schema.graph(lang, schema.pageNodes({
      url: canonical, type: PAGE_TYPES[id], name: data.title, description: data.description, lang,
      image, imageAlt: site.OG_ALT[lang], crumbs, about: id !== 'privacy',
    }))];
  }

  const head = {
    title: data.title,
    description: data.description,
    keywords: data.keywords,
    canonical,
    robots: is404 ? 'noindex' : undefined,
    alternates: hasPair ? layout.alternatesFor(id) : [],
    og: {
      type: 'website',
      title: data.title,
      image,
      imageWidth: og.width,
      imageHeight: og.height,
      imageAlt: site.OG_ALT[lang],
      alternateLocales: hasPair ? [layout.LOCALES[lang === 'sk' ? 'en' : 'sk']] : [],
    },
    jsonlds,
    verification,
    rawHead: id === 'home' && lang === 'sk' ? HASH_REDIRECT : undefined,
  };

  const bodyScripts = id === 'contact'
    ? fs.readFileSync(path.join(ROOT, 'templates/partials/contact-form.js'), 'utf8').replace('__MSG__', JSON.stringify(CONTACT_MSG[lang], null, 8).replace(/\n}/, '\n    }'))
    : '';

  return layout.renderDocument({
    generated: GENERATED,
    lang,
    active: is404 || id === 'privacy' ? null : id,
    switchTo: hasPair ? { sk: p.sk, en: p.en } : null,
    head,
    main,
    bodyScripts,
  });
}

function outputs() {
  const list = [];
  for (const id of Object.keys(PAGES)) {
    for (const lang of LANGS) if (PAGES[id][lang]) list.push({ id, lang, url: PAGES[id][lang] });
  }
  list.push({ id: '404', lang: 'sk', url: null, fileName: '404.html' });
  return list;
}

function main() {
  const outRoot = path.resolve(arg('out') || ROOT);
  const ctx = {
    translations: site.loadTranslations(),
    pages: site.loadPagesData(),
    copy: site.loadSiteCopy(),
    config: site.loadSiteConfig(),
    articles: loadArticles(path.resolve(process.env.ARTICLES_CONTENT_DIR || path.join(ROOT, 'content', 'articles'))),
  };
  let n = 0;
  for (const o of outputs()) {
    const dest = o.fileName ? path.join(outRoot, o.fileName) : site.urlToFile(outRoot, o.url);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, render(o.id, o.lang, ctx));
    n++;
  }
  console.log(`build-pages: ${n} pages written`);
}

if (require.main === module) main();

module.exports = { main, outputs };
