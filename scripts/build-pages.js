/*
 * Static generator for the main site pages (SK + EN).
 *
 *   node scripts/build-pages.js [--out DIR]
 *
 * Reads templates/pages/*.html (markup with data-i18n hooks and {{url:id}}
 * link tokens), translations.js and content/pages.json, and writes real
 * crawlable pages: /, /o-nas/, /sluzby/, /kontakt/, /ochrana-osobnych-udajov/,
 * /en/, /en/about/, /en/services/, /en/contact/ and /404.html. Zero dependencies.
 */

