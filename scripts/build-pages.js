const PAGE_TYPES = { about: 'AboutPage', contact: 'ContactPage' };

function ownersAsOf() {
  const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'owners.json'), 'utf8'));
  const [y, m, d] = cfg.asOf.split('-').map(Number);
  return `${d}. ${m}. ${y}`.replace(/ /g, '\u00a0');
}

function render(id, lang, ctx) {
  const file = `templates/pages/${id}.html`;
  const tpl = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const t = ctx.translations[lang];
  let main = applyI18n(tpl, t, lang, file);
  main = applyPlaceholders(main, t, lang, file);
  main = applyPictures(main, t, lang, file);
  main = applySak(main, ctx.config);
  main = applyLinkedIn(main, ctx.config);
  main = applyLatest(main, lang, ctx.copy, ctx.articles, t);
  main = applyServices(main, t, lang);
  main = applyServicesHero(main, t, lang);
  main = main.replace('{{hero}}', () => heroFor(id, lang, t, { ...ctx, ownersAsOf: ownersAsOf() }));
  main = main.replace('{{specialisation}}', () => specialisationBand(lang, t));
  main = main.replace('{{reviews}}', () => reviewsBand(lang, t));
  main = applyContactBand(main, t, lang);
  main = applyUi(main, t, lang, file);
  main = applyUrls(main, lang, file);
  if (id === 'owners') main = applyOwners(main);

  const data = (ctx.pages[id] || {})[lang];
  if (!data || !data.title || !data.description) fail(`content/pages.json: missing title/description for ${id}/${lang}`);

  const p = PAGES[id];
  const hasPair = !!(p && p.en);
  const is404 = id === '404';
  const canonical = is404 ? null : abs(p[lang]);
  const og = site.OG_IMAGES[lang];
  const image = abs(og.path);

  const verification = [];
  if (id === 'home' && lang === 'sk') {
    if (ctx.config.googleSiteVerification) verification.push(`<meta name="google-site-verification" content="${layout.esc(ctx.config.googleSiteVerification)}"/>`);
    if (ctx.config.bingSiteVerification) verification.push(`<meta name="msvalidate.01" content="${layout.esc(ctx.config.bingSiteVerification)}"/>`);
  }

  let jsonlds = [];
  if (!is404) {
    const crumbs = id === 'home' ? null : [
      { name: t['nav.home'], url: abs(PAGES.home[lang]) },
      { name: crumbName(id, t), url: canonical },
    ];
    jsonlds = [schema.graph(lang, schema.pageNodes({
      url: canonical, type: PAGE_TYPES[id], name: data.title, description: data.description, lang,
      image, imageAlt: site.OG_ALT[lang], crumbs, about: id !== 'privacy',
    }))];
  }

  const head = {
    title: data.title,
    description: data.description,
    keywords: data.keywords,
    canonical,
    robots: is404 || (p && p.hidden) ? 'noindex' : undefined,
    alternates: hasPair ? layout.alternatesFor(id) : [],
    og: {
      type: 'website',
      title: data.title,
      image,
      imageWidth: og.width,
      imageHeight: og.height,
      imageAlt: site.OG_ALT[lang],
      alternateLocales: hasPair ? [layout.LOCALES[lang === 'sk' ? 'en' : 'sk']] : [],
    },
    jsonlds,
    verification,
    rawHead: id === 'home' && lang === 'sk' ? HASH_REDIRECT : undefined,
  };

  // Page scripts keep their analytics calls between `// analytics:start` and `// analytics:end` lines;
  // they are dropped unless analytics is enabled, so the pages stay byte-identical without it.
  // Safe minification of an inline script: drops block comments and whole-line comments, trailing `// ...`
  // comments (only when the code before them has balanced quotes), blank lines and leading indentation.
  // No identifier mangling and every remaining line break stays, so ASI behaves exactly as before.
  const minifyInline = (src) => {
    const balanced = (code) => ['\'', '"'].every((q) => (code.replace(/\\./g, '').split(q).length - 1) % 2 === 0);
    let inBlock = false;
    const out = [];
    for (let line of src.split('\n')) {
      if (inBlock) {
        const end = line.indexOf('*/');
        if (end === -1) continue;
        inBlock = false;
        line = line.slice(end + 2);
      }
      let t = line.trim();
      if (t.startsWith('/*')) {
        const end = t.indexOf('*/', 2);
        if (end === -1) { inBlock = true; continue; }
        t = t.slice(end + 2).trim();
      }
      if (t.startsWith('//')) continue;
      const m = /\s\/\/\s/.exec(t);
      if (m && balanced(t.slice(0, m.index))) t = t.slice(0, m.index).trimEnd();
      if (t) out.push(t);
    }
    return out.join('\n');
  };
  const readScript = (f) => {
    const src = fs.readFileSync(path.join(ROOT, 'templates/partials', f), 'utf8');
    return layout.analytics() ? src : src.replace(/^[ \t]*\/\/ analytics:start\n[\s\S]*?^[ \t]*\/\/ analytics:end\n/gm, '');
  };
  let bodyScripts = '';
  if (id === 'contact') {
    bodyScripts = readScript('contact-form.js').replace('__MSG__', JSON.stringify(CONTACT_MSG[lang], null, 8).replace(/\n}/, '\n    }'));
  } else if (id === 'owners') {
    bodyScripts = minifyInline(readScript('owners-search.js'));
  }

  return layout.renderDocument({
    generated: GENERATED,
    lang,
    active: is404 || id === 'privacy' ? null : id,
    switchTo: hasPair ? { sk: p.sk, en: p.en } : null,
    head,
    main,
    bodyScripts,
  });
}

function outputs() {
  const list = [];
  for (const id of Object.keys(PAGES)) {
    for (const lang of LANGS) if (PAGES[id][lang]) list.push({ id, lang, url: PAGES[id][lang] });
  }
  list.push({ id: '404', lang: 'sk', url: null, fileName: '404.html' });
  return list;
}

function main() {
  const outRoot = path.resolve(arg('out') || ROOT);
  const ctx = {
    translations: site.loadTranslations(),
    pages: site.loadPagesData(),
    copy: site.loadSiteCopy(),
    config: site.loadSiteConfig(),
    articles: loadArticles(path.resolve(process.env.ARTICLES_CONTENT_DIR || path.join(ROOT, 'content', 'articles'))),
  };
  let n = 0;
  for (const o of outputs()) {
    const dest = o.fileName ? path.join(outRoot, o.fileName) : site.urlToFile(outRoot, o.url);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, render(o.id, o.lang, ctx));
    n++;
  }
  console.log(`build-pages: ${n} pages written`);
}

if (require.main === module) main();

