// content/pages/<slug>.md -> service landing pages (JSON front matter + the same markdown subset).
function loadServices(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.md')).sort()) {
    const file = path.join(dir, f);
    const raw = fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
    const m = /^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n([\s\S]*))?$/.exec(raw);
    if (!m) fail(`${file}: missing front matter`);
    let meta;
    try { meta = JSON.parse(m[1]); } catch (e) { fail(`${file}: front matter is not valid JSON (${e.message})`); }
    for (const k of ['seoTitle', 'description', 'h1', 'lead', 'date']) {
      if (typeof meta[k] !== 'string' || !meta[k]) fail(`${file}: missing field "${k}"`);
    }
    const slug = f.replace(/\.md$/, '');
    const body = (m[2] || '').trim();
    out.push({ ...meta, slug, url: site.serviceUrl(slug), body, html: markdown(body) });
  }
  return out;
}

function main() {
  const contentDir = path.resolve(arg('content') || process.env.ARTICLES_CONTENT_DIR || path.join(ROOT, 'content', 'articles'));
  const outRoot = path.resolve(arg('out') || process.env.ARTICLES_OUT_DIR || ROOT);
  const articles = loadArticles(contentDir);
  const services = loadServices(path.join(ROOT, 'content', 'pages'));
  for (const a of articles) {
    if (a.service && !services.some((x) => x.slug === a.service)) fail(`${a.file}: unknown service "${a.service}"`);
    const size = jpegSize(path.join(outRoot, 'assets', 'articles', `${a.image}.jpg`)) || jpegSize(path.join(ROOT, 'assets', 'articles', `${a.image}.jpg`));
    a.imgW = size ? size.width : 1600;
    a.imgH = size ? size.height : 1067;
  }
  const ctx = {
    outRoot, services,
    copy: site.loadSiteCopy(),
    config: site.loadSiteConfig(),
    pages: site.loadPagesData(),
  };
  const outDir = path.join(outRoot, 'clanky');
  fs.mkdirSync(outDir, { recursive: true });

  // Remove stale generated article dirs.
  const slugs = new Set(articles.map((a) => a.slug));
  let removed = 0;
  for (const d of fs.readdirSync(outDir, { withFileTypes: true })) {
    if (!d.isDirectory() || slugs.has(d.name)) continue;
    const idx = path.join(outDir, d.name, 'index.html');
    if (fs.existsSync(idx) && fs.readFileSync(idx, 'utf8').includes(GENERATED)) {
      fs.rmSync(path.join(outDir, d.name), { recursive: true, force: true });
      removed++;
    }
  }

  fs.writeFileSync(path.join(outDir, 'index.html'), listingPage(articles, ctx));
  for (const a of articles) {
    const dir = path.join(outDir, a.slug);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), articlePage(a, articles, ctx));
    fs.writeFileSync(path.join(dir, 'index.md'), mdCopy(a));
    const imgDir = path.join(outRoot, 'assets', 'articles');
    for (const f of [`${a.image}.jpg`, `${a.image}-800.jpg`, `${a.image}.avif`, `${a.image}-800.avif`]) {
      if (!fs.existsSync(path.join(imgDir, f))) console.warn(`build-articles: warning: ${a.file}: image not found: assets/articles/${f}`);
    }
  }
  for (const svc of services) {
    const dir = path.join(outRoot, svc.url.replace(/^\//, ''));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), servicePage(svc, articles, ctx));
  }
  writeLlmsFull(outRoot, articles);
  console.log(`build-articles: ${articles.length} articles + listing + ${services.length} service page(s) written, ${removed} stale dir(s) removed`);
  articles.services = services;
  return articles;
}

if (require.main === module) main();

module.exports = { main, loadArticles, loadServices, mdCopy, MONTHS };
