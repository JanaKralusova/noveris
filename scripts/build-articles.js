// The layout supplies the <main> wrapper.
function stripMain(html) {
  return html.replace(/^<main>\n?/, '').replace(/\n?<\/main>$/, '');
}

const SK_CRUMB = { home: 'Domov', articles: 'Články' };
const ogFor = (img, w, h, alt, extra) => ({ image: img, imageWidth: w, imageHeight: h, imageAlt: alt, ...extra });

function listingPage(articles, ctx) {
  const canonical = `${SITE}/clanky/`;
  const meta = ctx.pages.articles.sk;
  const l = ctx.copy.articlesListing;
  const og = site.OG_IMAGES.sk;
  const ogImage = abs(og.path);
  const ld = schema.graph('sk', schema.pageNodes({
    url: canonical, type: 'CollectionPage', name: meta.title, description: meta.description, lang: 'sk',
    image: ogImage, imageAlt: site.OG_ALT.sk,
    crumbs: [{ name: SK_CRUMB.home, url: `${SITE}/` }, { name: SK_CRUMB.articles, url: canonical }],
    extra: {
      mainEntity: {
        '@type': 'ItemList',
        numberOfItems: articles.length,
        itemListElement: articles.map((a, i) => ({ '@type': 'ListItem', position: i + 1, url: `${SITE}/clanky/${a.slug}/`, name: a.title })),
      },
    },
  }));
  const headData = {
    title: meta.title, description: meta.description, canonical,
    og: { type: 'website', title: meta.title, ...ogFor(ogImage, og.width, og.height, site.OG_ALT.sk) },
    jsonlds: [ld],
  };
  const main = `<main>
${ui.hero({
  crumbs: [{ name: SK_CRUMB.home, url: '/' }, { name: SK_CRUMB.articles }], crumbsLabel: 'Omrvinková navigácia',
  label: l.label, titleHtml: l.h1Html, intro: [l.intro],
  photo: { src: '/assets/photos/services/books_row', alt: '', sizes: '(min-width: 1024px) 62vw, 100vw', eager: true },
})}
${ui.section(`<div class="grid gap-5 md:grid-cols-2 lg:grid-cols-3 lg:gap-6">
${articles.map((a) => tile(a, { level: 2, root: ctx.outRoot })).join('\n')}
</div>`, { pad: 'pb-12 md:pb-16' })}
</main>`;
  return renderDocument({ generated: GENERATED, lang: 'sk', active: 'articles', switchTo: null, head: headData, main: stripMain(main) });
}

function articlePage(a, all, ctx) {
  const canonical = `${SITE}/clanky/${a.slug}/`;
  const title = a.seoTitle || `${a.title} | ${SITE_NAME}`;
  const imgUrl = `${SITE}/assets/articles/${a.image}.jpg`;
  const rel = related(a, all);
  const crumbs = [
    { name: SK_CRUMB.home, url: `${SITE}/` },
    { name: SK_CRUMB.articles, url: `${SITE}/clanky/` },
    { name: a.title, url: canonical },
  ];
  const modified = a.updated || a.date;
  const pageNodes = schema.pageNodes({
    url: canonical, type: 'WebPage', name: title, description: a.description, lang: 'sk',
    image: imgUrl, imageAlt: a.imageAlt, crumbs, about: false,
    extra: { mainEntity: schema.ref(`${canonical}#article`), datePublished: a.date, dateModified: modified },
  });
  const article = {
    '@type': 'Article',
    '@id': `${canonical}#article`,
    headline: a.title,
    description: a.description,
    image: schema.ref(`${canonical}#primaryimage`),
    datePublished: a.date,
    dateModified: modified,
    inLanguage: 'sk',
    keywords: a.keywords.join(', '),
    wordCount: a.words,
    about: a.tags.map((t) => ({ '@type': 'Thing', name: t })),
    author: schema.ref(schema.ID.person),
    publisher: schema.ref(schema.ID.org),
    isPartOf: schema.ref(`${canonical}#webpage`),
    mainEntityOfPage: schema.ref(`${canonical}#webpage`),
  };
  const faq = a.faq.length && {
    '@type': 'FAQPage',
    '@id': `${canonical}#faq`,
    inLanguage: 'sk',
    isPartOf: schema.ref(`${canonical}#webpage`),
    mainEntity: a.faq.map((f) => ({ '@type': 'Question', name: f.question, acceptedAnswer: { '@type': 'Answer', text: f.answer } })),
  };
  const headData = {
    title, description: a.description, canonical, keywords: a.keywords.join(', '),
    og: {
      type: 'article', title: a.title, author: AUTHOR,
      ...ogFor(imgUrl, a.imgW, a.imgH, a.imageAlt),
      extra: [
        `<meta property="article:published_time" content="${esc(a.date)}"/>`,
        `<meta property="article:modified_time" content="${esc(modified)}"/>`,
        ...a.tags.map((t) => `<meta property="article:tag" content="${esc(t)}"/>`),
      ],
    },
    jsonlds: [schema.graph('sk', [...pageNodes, article, ...(faq ? [faq] : [])])], mdAlt: `/clanky/${a.slug}/index.md`,
  };
  const crumbItems = [{ name: SK_CRUMB.home, url: '/' }, { name: SK_CRUMB.articles, url: '/clanky/' }, { name: a.title }];
  const main = `<main>
${ui.hero({
  topHtml: `<a href="/clanky/" class="mb-4 mt-4 inline-flex items-center gap-1.5 font-label text-[13px] font-semibold text-copper hover:text-forest">${ui.icon('arrow_back', 'text-[18px]')}Všetky články</a>`,
  crumbs: crumbItems, crumbsLabel: 'Omrvinková navigácia',
  title: a.title, size: 'long',
  extraHtml: `<div class="mt-6 flex flex-wrap items-center gap-x-5 gap-y-3">
<a href="/o-nas/" class="flex items-center gap-3 font-label text-[14px] font-semibold text-ink hover:text-copper">${authorAvatar('h-10 w-10')}${esc(AUTHOR)}, advokátka</a>
<time datetime="${esc(a.date)}" class="font-label text-[13px] text-muted">${esc(formatDate(a.date))}</time>
</div>
<ul class="mt-4 flex flex-wrap gap-2" aria-label="Značky">
${a.tags.map((t) => `<li class="rounded-pill bg-chip px-3 py-1 font-label text-[12px] text-copper">${esc(t)}</li>`).join('\n')}
</ul>`,
  photo: { src: `/assets/articles/${a.image}`, variants: articleVariants(a.image, ctx.outRoot), fallback: '800', sizes: ARTICLE_HERO_SIZES, alt: a.imageAlt, eager: true, root: ctx.outRoot },
})}
<article class="mx-auto max-w-7xl px-6 pb-8 pt-4 lg:px-8 lg:pb-12">
<div class="mt-2 grid gap-12 lg:grid-cols-[minmax(0,1fr)_320px] lg:gap-14">
<div class="max-w-[46rem]">
${toc(a)}
<div class="article-body mt-8">
${a.html}
</div>
</div>
<div class="lg:pt-8">
${authorBox(a, ctx)}
</div>
</div>
</article>

${closingBand(TR)}
${rel.length ? ui.section(`${ui.sectionHeader({ eyebrow: 'Čítajte ďalej', title: 'Súvisiace články' })}<div class="grid gap-5 md:grid-cols-3 lg:gap-6">
${rel.map((r) => tile(r, { root: ctx.outRoot })).join('\n')}
</div>`, { bg: 'sand' }) : ''}</main>`;
  return renderDocument({ generated: GENERATED, lang: 'sk', active: 'articles', switchTo: null, head: headData, main: stripMain(main) });
}

// ---------------------------------------------------------------- markdown copies & llms

function mdCopy(a) {
  return `# ${a.title}\n\n${SITE}/clanky/${a.slug}/\nDátum: ${a.date}\nTagy: ${a.tags.join(', ')}\n\n${a.body}\n`;
}


function writeLlmsFull(outRoot, articles) {
  const head = `# Noveris Legal – články (úplné znenie)\n\n> Úplné znenie článkov z ${SITE}/clanky/. Zdroj: advokátska kancelária Noveris Legal, ${AUTHOR}.\n`;
  fs.writeFileSync(path.join(outRoot, 'llms-full.txt'), head + '\n' + articles.map(mdCopy).join('\n---\n\n'));
}

// ---------------------------------------------------------------- main

function main() {
  const contentDir = path.resolve(arg('content') || process.env.ARTICLES_CONTENT_DIR || path.join(ROOT, 'content', 'articles'));
  const outRoot = path.resolve(arg('out') || process.env.ARTICLES_OUT_DIR || ROOT);
  const articles = loadArticles(contentDir);
  for (const a of articles) {
    const size = jpegSize(path.join(outRoot, 'assets', 'articles', `${a.image}.jpg`)) || jpegSize(path.join(ROOT, 'assets', 'articles', `${a.image}.jpg`));
    a.imgW = size ? size.width : 1600;
    a.imgH = size ? size.height : 1067;
  }
  const ctx = {
    outRoot,
    copy: site.loadSiteCopy(),
    config: site.loadSiteConfig(),
    pages: site.loadPagesData(),
  };
  const outDir = path.join(outRoot, 'clanky');
  fs.mkdirSync(outDir, { recursive: true });

  // Remove stale generated article dirs.
  const slugs = new Set(articles.map((a) => a.slug));
  let removed = 0;
  for (const d of fs.readdirSync(outDir, { withFileTypes: true })) {
    if (!d.isDirectory() || slugs.has(d.name)) continue;
    const idx = path.join(outDir, d.name, 'index.html');
    if (fs.existsSync(idx) && fs.readFileSync(idx, 'utf8').includes(GENERATED)) {
      fs.rmSync(path.join(outDir, d.name), { recursive: true, force: true });
      removed++;
    }
  }

  fs.writeFileSync(path.join(outDir, 'index.html'), listingPage(articles, ctx));
  for (const a of articles) {
    const dir = path.join(outDir, a.slug);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), articlePage(a, articles, ctx));
    fs.writeFileSync(path.join(dir, 'index.md'), mdCopy(a));
    const imgDir = path.join(outRoot, 'assets', 'articles');
    for (const f of articleVariants(a.image, outRoot).flatMap((w) => ['jpg', 'avif'].map((ext) => `${a.image}${w ? '-' + w : ''}.${ext}`))) {
      if (!fs.existsSync(path.join(imgDir, f))) console.warn(`build-articles: warning: ${a.file}: image not found: assets/articles/${f}`);
    }
  }
  writeLlmsFull(outRoot, articles);
  console.log(`build-articles: ${articles.length} articles + listing written, ${removed} stale dir(s) removed`);
  return articles;
}

if (require.main === module) main();

