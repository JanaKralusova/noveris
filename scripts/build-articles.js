/*
 * Static generator for the "Články" (articles) section.
 *
 *   node scripts/build-articles.js [--content DIR] [--out DIR]
 *
 * Reads content/articles/*.md (JSON front matter between two `---` lines +
 * a small markdown subset) and writes clanky/index.html, clanky/<slug>/index.html
 * llms-full.txt. The sitemap and llms.txt are owned by scripts/build.js (which
 * calls this module). Zero dependencies.
 *
 * Env alternatives: ARTICLES_CONTENT_DIR, ARTICLES_OUT_DIR (site root to write to;
 * defaults to the repo root).
 */

