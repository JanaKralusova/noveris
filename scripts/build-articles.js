// ---------------------------------------------------------------- utilities

function arg(name) {
  const i = process.argv.indexOf('--' + name);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

function fail(msg) {
  console.error('build-articles: ERROR: ' + msg);
  process.exit(1);
}

const MONTHS = ['januára', 'februára', 'marca', 'apríla', 'mája', 'júna', 'júla',
  'augusta', 'septembra', 'októbra', 'novembra', 'decembra'];

function formatDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return `${d}. ${MONTHS[m - 1]} ${y}`;
}

// ---------------------------------------------------------------- markdown

function inline(raw) {
  const holders = [];
  // Links first (on raw text), replaced by placeholders so later passes cannot touch them.
  let text = raw.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => {
    const safe = /^(https?:\/\/|mailto:|tel:|\/|#|\.{1,2}\/)/i.test(url);
    const labelHtml = emphasis(esc(label));
    let html;
    if (!safe) html = labelHtml;
    else {
      const ext = /^https?:\/\//i.test(url);
      html = `<a href="${esc(url)}"${ext ? ' rel="noopener" target="_blank"' : ''}>${labelHtml}</a>`;
    }
    holders.push(html);
    return `\u0000${holders.length - 1}\u0000`;
  });
  text = emphasis(esc(text));
  return text.replace(/\u0000(\d+)\u0000/g, (_, i) => holders[Number(i)]);
}

function emphasis(escaped) {
  return escaped
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\*(.+?)\*/g, '<em>$1</em>');
}

function slugify(t) {
  return t.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'cast';
}

function stripInline(t) {
  return t.replace(/\[([^\]]+)\]\([^)\s]+\)/g, '$1').replace(/\*+/g, '');
}

function markdown(src, headings) {
  const usedIds = new Set();
  const lines = src.replace(/\r\n?/g, '\n').split('\n');
  const out = [];
  let para = [];
  let list = null; // { tag, items: [] }

  const flushPara = () => {
    if (para.length) out.push(`<p>${inline(para.join(' '))}</p>`);
    para = [];
  };
  const flushList = () => {
    if (list) {
      out.push(`<${list.tag}>\n${list.items.map((i) => `<li>${inline(i)}</li>`).join('\n')}\n</${list.tag}>`);
    }
    list = null;
  };

  for (const line of lines) {
    let m;
    if (/^\s*$/.test(line)) { flushPara(); flushList(); continue; }
    if ((m = /^(#{2,3})\s+(.*?)\s*#*\s*$/.exec(line))) {
      flushPara(); flushList();
      const n = m[1].length;
      let id = '';
      if (n === 2) {
        const base = slugify(stripInline(m[2]));
        id = base; let k = 2;
        while (usedIds.has(id)) id = `${base}-${k++}`;
        usedIds.add(id);
        if (headings) headings.push({ id, text: stripInline(m[2]) });
      }
      out.push(`<h${n}${id ? ` id="${id}"` : ''}>${inline(m[2])}</h${n}>`);
    } else if ((m = /^\s*[-*]\s+(.*)$/.exec(line)) && !/^\s*\*\*/.test(line)) {
      flushPara();
      if (!list || list.tag !== 'ul') { flushList(); list = { tag: 'ul', items: [] }; }
      list.items.push(m[1].trim());
    } else if ((m = /^\s*\d+[.)]\s+(.*)$/.exec(line))) {
      flushPara();
      if (!list || list.tag !== 'ol') { flushList(); list = { tag: 'ol', items: [] }; }
      list.items.push(m[1].trim());
    } else if (list && /^\s+\S/.test(line)) {
      list.items[list.items.length - 1] += ' ' + line.trim();
    } else {
      flushList();
      para.push(line.trim());
    }
  }
  flushPara(); flushList();
  return out.join('\n');
}

// "## Časté otázky" section -> [{ question, answer }] (plain text) for FAQPage JSON-LD; [] when absent.
const FAQ_HEADING = 'Časté otázky';

function extractFaq(body, file) {
  const lines = body.replace(/\r\n?/g, '\n').split('\n');
  const items = [];
  let inFaq = false;
  let found = false;
  let cur = null;
  for (const line of lines) {
    let m;
    if ((m = /^##\s+(.*?)\s*#*\s*$/.exec(line))) {
      inFaq = stripInline(m[1]) === FAQ_HEADING;
      if (inFaq) found = true;
      cur = null;
    } else if (!inFaq) {
      continue;
    } else if ((m = /^###\s+(.*?)\s*#*\s*$/.exec(line))) {
      cur = { question: stripInline(m[1]), lines: [] };
      items.push(cur);
    } else if (cur) {
      cur.lines.push(line);
    }
  }
  if (found && !items.length) fail(`${file}: section "${FAQ_HEADING}" has no "### " question`);
  return items.map((it) => {
    const answer = stripInline(it.lines.join(' ')).replace(/\s+/g, ' ').trim();
    if (!answer) fail(`${file}: FAQ question "${it.question}" has an empty answer`);
    return { question: it.question, answer };
  });
}

// ---------------------------------------------------------------- loading

function loadArticles(dir) {
  if (!fs.existsSync(dir)) fail(`content directory not found: ${dir}`);
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
  if (!files.length) fail(`no .md files in ${dir}`);
  const articles = [];
  const slugs = new Set();

  for (const f of files) {
    const file = path.join(dir, f);
    const raw = fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
    const m = /^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n([\s\S]*))?$/.exec(raw);
    if (!m) fail(`${file}: missing front matter (expected JSON between two "---" lines)`);
    let meta;
    try { meta = JSON.parse(m[1]); } catch (e) { fail(`${file}: front matter is not valid JSON (${e.message})`); }
    if (!meta || typeof meta !== 'object' || Array.isArray(meta)) fail(`${file}: front matter must be a JSON object`);

    for (const k of REQUIRED) {
      if (meta[k] === undefined || meta[k] === null || meta[k] === '') fail(`${file}: missing required field "${k}"`);
    }
    for (const k of ['seoTitle']) {
      if (meta[k] !== undefined && typeof meta[k] !== 'string') fail(`${file}: field "${k}" must be a string`);
    }
    for (const k of ['slug', 'title', 'excerpt', 'description', 'image', 'imageAlt', 'date']) {
      if (typeof meta[k] !== 'string') fail(`${file}: field "${k}" must be a string`);
    }
    if (typeof meta.order !== 'number' || !isFinite(meta.order)) fail(`${file}: field "order" must be a number`);
    for (const k of ['tags', 'keywords']) {
      if (!Array.isArray(meta[k]) || meta[k].some((x) => typeof x !== 'string')) fail(`${file}: field "${k}" must be an array of strings`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(meta.slug)) fail(`${file}: invalid slug "${meta.slug}" (lowercase a-z, 0-9, hyphens)`);
    if (!/^[A-Za-z0-9._-]+$/.test(meta.image)) fail(`${file}: invalid image name "${meta.image}"`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date) || isNaN(Date.parse(meta.date))) fail(`${file}: "date" must be YYYY-MM-DD`);
    if (meta.updated !== undefined) {
      if (typeof meta.updated !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(meta.updated) || isNaN(Date.parse(meta.updated))) fail(`${file}: "updated" must be YYYY-MM-DD`);
      if (meta.updated < meta.date) fail(`${file}: "updated" (${meta.updated}) must not be earlier than "date" (${meta.date})`);
    }
    if (slugs.has(meta.slug)) fail(`${file}: duplicate slug "${meta.slug}"`);
    slugs.add(meta.slug);

    const body = (m[2] || '').trim();
    if (!body) fail(`${file}: empty article body`);
    const headings = [];
    const html = markdown(body, headings);
    const faq = extractFaq(body, file);
    const words = body.replace(/[#*\[\]()`>-]/g, ' ').split(/\s+/).filter(Boolean).length;
    articles.push({ ...meta, file, body, html, headings, faq, words });
  }
  articles.sort((a, b) => a.order - b.order);
  return articles;
}


// ---------------------------------------------------------------- components

function toc(a) {
  if (a.headings.length < 2) return '';
  return `<nav aria-label="Obsah článku" class="mt-8">
<details class="rounded-card border border-line bg-sand p-5" open>
<summary class="cursor-pointer select-none font-label text-[13px] font-semibold uppercase tracking-[0.14em] text-ink focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-forest/40">Obsah článku</summary>
<ol class="mt-3 list-decimal space-y-1.5 pl-5 text-[15px] marker:text-copper">
${a.headings.map((h) => `<li><a href="#${h.id}" class="text-body hover:text-copper">${esc(h.text)}</a></li>`).join('\n')}
</ol>
</details>
</nav>`;
}

function related(a, all) {
  const tags = new Set(a.tags);
  return all
    .filter((o) => o.slug !== a.slug)
    .map((o) => ({ o, shared: o.tags.filter((t) => tags.has(t)).length, dist: Math.abs(o.order - a.order) }))
    .sort((x, y) => y.shared - x.shared || x.dist - y.dist || x.o.order - y.o.order)
    .slice(0, 3)
    .map((x) => x.o);
}

